import { chromium } from "playwright";
const CHROME = `${process.env.HOME}/Library/Caches/ms-playwright/chromium-1248/chrome-mac-arm64/Google Chrome for Testing.app/Contents/MacOS/Google Chrome for Testing`;
const b = await chromium.launch({ executablePath: CHROME });
const p = await (await b.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
p.on("console", (m) => m.type() === "error" && console.log("ERR", m.text().slice(0, 200)));
p.on("pageerror", (e) => console.log("PAGEERR", e.message.slice(0, 200)));
const t = Date.now();
await p.goto("http://localhost:3000/app/pods/pod_hoopers/chat?mode=demo", { waitUntil: "domcontentloaded", timeout: 240000 });
console.log("dcl", Date.now() - t);
await p.waitForLoadState("load", { timeout: 240000 }).catch((e) => console.log("noload"));
console.log("load", Date.now() - t);
await b.close();
